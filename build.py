# builds the installable app (docs/) from index.html, the same file published on claude.ai
# run: python build.py   (ci fails if docs/ is out of date)
import base64, hashlib, json, re, shutil
from pathlib import Path

root = Path(__file__).parent
src = (root / "index.html").read_text(encoding="utf-8").replace("\r\n", "\n")  # a windows checkout may have crlf; the build must match ci byte for byte

# 1. the course lives in content/*.json (one file per stage, plus the fuṣḥā list and readings); it's compiled into
# index.html between the <content> markers so the page stays a single file that claude.ai can publish
def rows(name, key):
    f = root / "content" / name
    data = json.loads(f.read_text(encoding="utf-8")) if f.exists() else []
    return f"const {key}=[\n" + ",\n".join(json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in data) + "\n];\n"
units = []
for n in range(1, 6):  # a stage is content/stageN.json, then content/stageN/*.json in name order (lessons are written in batches)
    f = root / "content" / f"stage{n}.json"
    if f.exists(): units += json.loads(f.read_text(encoding="utf-8"))
    for g in sorted((root / "content" / f"stage{n}").glob("*.json"), key=lambda p: p.name):
        units += json.loads(g.read_text(encoding="utf-8"))
course = "const COURSE=[\n" + ",\n".join(json.dumps(u, ensure_ascii=False, separators=(",", ":")) for u in units) + "\n];\n"
block = ("// <content>\n// generated by build.py from content/*.json: edit those files, not this block. unit items are [ar, gulf translit,"
         " english, fuṣḥā equivalent or \"\", note or \"\"]; MSA rows are [vowelled ar, translit, english, gulf equivalent?, domain?]\n"
         + course + rows("msa.json", "MSA") + rows("readings.json", "READINGS") + "// </content>")
compiled = re.sub(r"// <content>.*?// </content>", lambda m: block, src, count=1, flags=re.S)
if compiled != src:
    (root / "index.html").write_text(compiled, encoding="utf-8", newline="\n")
    src = compiled
    print("compiled content/ into index.html")
out = root / "docs"

# google fonts aren't available offline, so the app ships its own copies
body = re.sub(r'<link rel="(preconnect|stylesheet)" href="https://fonts\.g[^"]*"[^>]*>\n?', "", src)
title = re.search(r"<title>(.*?)</title>", body).group(1)
body = body.replace(f"<title>{title}</title>\n", "", 1)
fonts = """<style>
@font-face{font-family:"Amiri";font-weight:400;font-display:swap;src:url(fonts/amiri-arabic-400-normal.woff2) format("woff2");unicode-range:U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0898-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC}
@font-face{font-family:"Amiri";font-weight:700;font-display:swap;src:url(fonts/amiri-arabic-700-normal.woff2) format("woff2");unicode-range:U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0898-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC}
@font-face{font-family:"Readex Pro";font-weight:400;font-display:swap;src:url(fonts/readex-pro-latin-400-normal.woff2) format("woff2");unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}
@font-face{font-family:"Readex Pro";font-weight:400;font-display:swap;src:url(fonts/readex-pro-latin-ext-400-normal.woff2) format("woff2");unicode-range:U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF}
@font-face{font-family:"Readex Pro";font-weight:500;font-display:swap;src:url(fonts/readex-pro-latin-500-normal.woff2) format("woff2")}
@font-face{font-family:"Readex Pro";font-weight:600;font-display:swap;src:url(fonts/readex-pro-latin-600-normal.woff2) format("woff2")}
</style>"""
sw = """<script>
// installed-app extras: offline support and asking the browser not to clear progress
window.HARF_PWA=true;
if("serviceWorker" in navigator) addEventListener("load",()=>navigator.serviceWorker.register("sw.js").catch(()=>{}));
if(navigator.storage&&navigator.storage.persist) navigator.storage.persist().catch(()=>{});
</script>
"""
rest = body.strip() + "\n" + sw
# csp: only this app's own inline scripts (by hash) and files from its own folder; nothing loads from other sites
hashes = " ".join(f"'sha256-{base64.b64encode(hashlib.sha256(js.encode()).digest()).decode()}'" for js in re.findall(r"<script[^>]*>(.*?)</script>", rest, re.S))
csp = f"default-src 'self'; script-src 'self' {hashes}; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' blob:; font-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'"
head = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="{csp}">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>{title}</title>
<meta name="description" content="Learn to speak Gulf Arabic from zero.">
<meta name="theme-color" content="#0f5f5a" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0d1513" media="(prefers-color-scheme: dark)">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/favicon-32.png" sizes="32x32">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Harf">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<style>:root{{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}}body{{margin:0}}img{{max-width:100%}}[hidden]{{display:none!important}}</style>
{fonts}
</head>
<body>
"""
html = head + rest + "</body>\n</html>\n"
sw_src = (root / "pwa" / "sw.js").read_text(encoding="utf-8").replace("\r\n", "\n")
# a new page, worker, icon or font gets a new cache (icons and fonts are served cache-first, so they'd never refresh otherwise)
assets = b"".join(f.relative_to(root).as_posix().encode() + f.read_bytes().replace(b"\r\n", b"\n") for f in sorted((root / "pwa").rglob("*"), key=lambda p: p.as_posix()) if f.is_file() and f.name != "sw.js")  # sort by the posix string: windows paths sort case-insensitively, which changed the build id
build = hashlib.sha256((html + sw_src).encode() + assets).hexdigest()[:10]

if out.exists(): shutil.rmtree(out)
shutil.copytree(root / "pwa", out)
(out / "sw.js").write_text(sw_src.replace("__BUILD__", build), encoding="utf-8", newline="\n")  # lf on windows too, so ci matches
(out / "index.html").write_text(html, encoding="utf-8", newline="\n")
(out / ".nojekyll").write_text("")
print(f"built docs/ ({build})")
